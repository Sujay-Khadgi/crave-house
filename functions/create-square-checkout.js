const sauces = ['Tomato Sauce','Burger Sauce','Buffalo Sauce','Mayonnaise','Garlic Aioli','Chipotle Mayo','Smoky BBQ','Peri-Peri Sauce','Ranch'];
function priceItem(item, menu) {
  const parts = String(item.variant || '').split(' | ');
  let price = menu.price;
  if (menu.prices) price = menu.prices[parts[0]?.replace(/^Size: /,'')];
  if (!Number.isFinite(price)) throw new Error('Invalid item size');
  let amount = cents(price);
  const allowed = menu.options ? {'Extra Cheese':200,'Extra Bacon':350,'Avocado':300} : menu.saladOptions ? {'Grilled chicken':500,'Crispy chicken':500,'Extra prawns':700,'Avocado':250} : ['sn1','sn2'].includes(item.itemId) ? Object.fromEntries(sauces.map(s=>['Extra '+s,200])) : {};
  const addons = item.addons || [];
  if (!Array.isArray(addons) || new Set(addons).size !== addons.length) throw new Error('Invalid extras');
  for (const addon of addons) { if (!Object.hasOwn(allowed,addon)) throw new Error('Invalid extra'); amount += allowed[addon]; }
  if (menu.buns && parts.some(p=>['Gluten-Free Bun (+$2.50)','Vegan Bun (+$2.50)'].includes(p))) amount += 250;
  const combos = {'Regular classic fries + 375 mL drink (+$7.00)':700,'Regular sweet potato fries + 375 mL drink (+$11.00)':1100,'Onion rings + 375 mL drink (+$12.00)':1200};
  if (menu.combos) { const combo = parts.find(p=>Object.hasOwn(combos,p)); if(combo) { amount += combos[combo]; if(parts.some(p=>/^(Coca-Cola|Sprite|Fanta) 600 mL$/.test(p))) amount += 200; } }
  return amount;
}
